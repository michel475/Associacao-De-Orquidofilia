import { Campo } from 'src/shared/database/decorators/campo-dec';
import { Tabela } from 'src/shared/database/decorators/tabela-dec';
import { SuperTabela } from 'src/shared/database/superTabela';
import { DatabaseDataType } from 'src/shared/database/utils/DatabaseDataType';

@Tabela({ tableName: 'reproducaoFlor' })
export class ReproducaoFlorEntity extends SuperTabela<number> {
  constructor(
    id: number,
    orquidarioId: number,
    hibridoNome: string,
    dataGerminacao: Date,
    viavel: boolean,
    taxaSucessoPct: number,
  ) {
    super();
    this.id = id;
    this.orquidarioId = orquidarioId;
    this.hibridoNome = hibridoNome;
    this.dataGerminacao = dataGerminacao;
    this.viavel = viavel;
    this.taxaSucessoPct = taxaSucessoPct;
  }

  @Campo({
    colunaNome: 'id',
    isPk: true,
    isObrigatorio: true,
    isAutoGenerated: true,
  })
  id: number;

  @Campo({ colunaNome: 'orquidarioId', isObrigatorio: true })
  orquidarioId: number;

  @Campo({ colunaNome: 'hibridoNome', isObrigatorio: true })
  hibridoNome: string;

  @Campo({ colunaNome: 'dataGerminacao', isObrigatorio: true })
  dataGerminacao: Date;

  @Campo({ colunaNome: 'viavel', isObrigatorio: true })
  viavel: boolean;

  @Campo({
    colunaNome: 'taxaSucessoPct',
    isObrigatorio: true,
    dataType: DatabaseDataType.DOUBLE,
  })
  taxaSucessoPct: number;
}
