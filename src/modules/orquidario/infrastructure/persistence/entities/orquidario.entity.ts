import { Tabela } from 'src/shared/database/decorators/tabela-dec';
import { Campo } from 'src/shared/database/decorators/campo-dec';
import { SuperTabela } from 'src/shared/database/superTabela';
import { DatabaseDataType } from 'src/shared/database/utils/DatabaseDataType';

@Tabela({ tableName: 'orquidario' })
export class OrquidarioEntity extends SuperTabela<number> {
  constructor(
    id: number,
    endereco: string,
    dataCriacao: Date,
    irrigadoAuto: boolean,
    areaMquadrados: number,
  ) {
    super();
    this.endereco = endereco;
    this.dataCriacao = dataCriacao;
    this.irrigadoAuto = irrigadoAuto;
    this.areaMquadrados = areaMquadrados;
  }

  @Campo({
    colunaNome: 'id',
    isPk: true,
    isObrigatorio: true,
    isAutoGenerated: true,
  })
  id: number;

  @Campo({ colunaNome: 'endereco', isObrigatorio: true})
  endereco: string;

  @Campo({ colunaNome: 'dataCriacao', isObrigatorio: true })
  dataCriacao: Date;

  @Campo({ colunaNome: 'irrigadoAuto', isObrigatorio: true })
  irrigadoAuto: boolean;

  @Campo({
    colunaNome: 'areaMquadrados',
    isObrigatorio: true,
    dataType: DatabaseDataType.DOUBLE,
  })
  areaMquadrados: number;
}
