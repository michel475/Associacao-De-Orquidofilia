import { CampoMetadata } from "../decorators/campo-dec";
import { SuperTabela } from "../superTabela";
import { ReflexaoTabela } from "./ReflexaoTabela";
import type { ConstrutorTabela } from "./ReflexaoTabela";
import { normalizeData } from "./DatabaseDataType";

export interface PreparedInsert {
    sql: string;
    parameters: unknown[];
}

export class SQLGen {
    public criarTabela(entidade: ConstrutorTabela): string {
        const tabela = ReflexaoTabela.getTableName(entidade);
        const campos: CampoMetadata[] = ReflexaoTabela.getCampos(entidade);

        if (campos.length === 0) {
            throw new Error(`A classe ${entidade.name} não possui campos @Campo para gerar a tabela.`);
        }

        const definicoes = campos.map((campo) => {
            const restricoes = [
                campo.isPk ? "PRIMARY KEY" : undefined,
                campo.isAutoGenerated ? "AUTOINCREMENT" : undefined,
                campo.isObrigatorio ? "NOT NULL" : undefined,
            ].filter((restricao): restricao is string => restricao !== undefined);

            return `  ${this.quoteIdentifier(campo.colunaNome)} ${campo.dataType}${
                restricoes.length > 0 ? ` ${restricoes.join(" ")}` : ""
            }`;
        });

        return `CREATE TABLE IF NOT EXISTS ${this.quoteIdentifier(tabela)} (\n${definicoes.join(",\n")}\n);`;
    }

    private quoteIdentifier(identifier: string): string {
        return `"${identifier.replace(/"/g, '""')}"`;
    }

    public selecionarTodos(entidade: ConstrutorTabela): string {
        const tabela = ReflexaoTabela.getTableName(entidade);
        this.validarCampos(entidade);
        return `SELECT * FROM ${this.quoteIdentifier(tabela)}`;
    }

    public selecionarPorPk(entidade: ConstrutorTabela): string {
        const tabela = ReflexaoTabela.getTableName(entidade);
        const campos = this.validarCampos(entidade);
        const campoPk = campos.find((campo) => campo.isPk);
        if (!campoPk) {
            throw new Error(
                `Classe ${entidade.name} não possui um campo @Campo({ isPk: true }).`,
            );
        }
        return `SELECT * FROM ${this.quoteIdentifier(tabela)} WHERE ${this.quoteIdentifier(campoPk.colunaNome)} = ?`;
    }

    private validarCampos(entidade: ConstrutorTabela): CampoMetadata[] {
        const campos = ReflexaoTabela.getCampos(entidade);
        if (campos.length === 0) {
            throw new Error(
                `A classe ${entidade.name} não possui campos @Campo para consultar.`,
            );
        }
        const nomesColunas = campos.map((campo) => campo.colunaNome);
        if (new Set(nomesColunas).size !== nomesColunas.length) {
            throw new Error(
                `A classe ${entidade.name} possui nomes de coluna @Campo duplicados.`,
            );
        }
        return campos;
    }

    public inserirTupla(obj: SuperTabela<unknown>): PreparedInsert {
        const tabela = ReflexaoTabela.getTableName(obj);
        const campos: CampoMetadata[] = ReflexaoTabela.getCampos(obj);

        if (campos.length === 0) {
            throw new Error(`A classe ${obj.constructor.name} não possui campos @Campo para inserir.`);
        }

        const nomesColunas = campos.map((campo) => campo.colunaNome);
        if (new Set(nomesColunas).size !== nomesColunas.length) {
            throw new Error(`A classe ${obj.constructor.name} possui nomes de coluna @Campo duplicados.`);
        }

        const camposInseriveis = campos.filter((campo) => !campo.isAutoGenerated);
        const camposComValores = camposInseriveis.map((campo) => ({
            campo,
            valor: ReflexaoTabela.getCampoValor(obj, campo.propriedade),
        }));
        const obrigatoriosAusentes = camposComValores
            .filter(
                ({ campo, valor }) =>
                    campo.isObrigatorio &&
                    (valor === null || valor === undefined || valor === ""),
            )
            .map(({ campo }) => campo.propriedade);
        if (obrigatoriosAusentes.length > 0) {
            throw new Error(
                `Campos obrigatórios não preenchidos em ${obj.constructor.name}: ${obrigatoriosAusentes.join(", ")}.`,
            );
        }

        if (camposInseriveis.length === 0) {
            return {
                sql: `INSERT INTO ${this.quoteIdentifier(tabela)} DEFAULT VALUES`,
                parameters: [],
            };
        }

        const parameters = camposComValores.map(({ campo, valor }) => {
            if (valor === undefined) {
                throw new Error(
                    `O campo ${obj.constructor.name}.${campo.propriedade} está indefinido.`,
                );
            }

            try {
                return normalizeData(valor, campo.dataType);
            } catch (error) {
                const detalhe =
                    error instanceof Error ? error.message : String(error);
                throw new Error(
                    `Valor inválido em ${obj.constructor.name}.${campo.propriedade}: ${detalhe}`,
                    { cause: error },
                );
            }
        });

        const colunasSql = camposInseriveis
            .map((campo) => this.quoteIdentifier(campo.colunaNome))
            .join(", ");
        const placeholders = camposInseriveis.map(() => "?").join(", ");

        return {
            sql: `INSERT INTO ${this.quoteIdentifier(tabela)} (${colunasSql}) VALUES (${placeholders})`,
            parameters,
        };
    }
}