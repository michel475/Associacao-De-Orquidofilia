import "reflect-metadata";
import { Campo } from "../decorators/campo-dec";
import { Tabela } from "../decorators/tabela-dec";
import { SuperTabela } from "../superTabela";
import { DatabaseDataType } from "./DatabaseDataType";
import { SQLGen } from "./SQL-Gen";
import {
    SQLInsertExecutor,
    SQLQueryExecutor,
    SQLExecutionResult,
} from "./SQL-Insert-Executor";

@Tabela({ tableName: "teste" })
class TabelaTeste extends SuperTabela<number> {
    @Campo({
        colunaNome: "id",
        isPk: true,
        isObrigatorio: true,
        isAutoGenerated: true,
    })
    private id!: number;

    @Campo({ colunaNome: "nome", isObrigatorio: true })
    private nome!: string;

    @Campo({ colunaNome: "criado_em" })
    private criadoEm!: Date;

    @Campo({ colunaNome: "ativo" })
    private ativo!: boolean;

    @Campo({ colunaNome: "valor", dataType: DatabaseDataType.DOUBLE })
    private valor!: number;

    constructor() {
        super();
        this.id = 12;
        this.nome = `Orquídea d'água`;
        this.criadoEm = new Date("2026-10-20T16:00:00.000Z");
        this.ativo = false;
        this.valor = 1.5;
    }

    public getNome(): string {
        return this.nome;
    }
}

@Tabela({ tableName: "somente_id" })
class TabelaSomenteId extends SuperTabela<number> {
    @Campo({
        colunaNome: "id",
        isPk: true,
        isObrigatorio: true,
        isAutoGenerated: true,
    })
    private id!: number;
}

@Tabela({ tableName: "invalida" })
class TabelaObrigatoriaInvalida extends SuperTabela<number> {
    @Campo({ colunaNome: "nome", isObrigatorio: true })
    private nome!: string;
}

@Tabela({ tableName: "valor_invalido" })
class TabelaValorInvalido extends SuperTabela<number> {
    @Campo({ colunaNome: "valor", dataType: DatabaseDataType.DOUBLE })
    private valor = Number.NaN;
}

describe("SQLGen", () => {
    it("gera DDL SQLite usando os tipos e restrições dos metadados refletidos", () => {
        const sql = new SQLGen().criarTabela(TabelaTeste);

        expect(sql).toBe(
            [
                'CREATE TABLE IF NOT EXISTS "teste" (',
                '  "id" INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL,',
                '  "nome" VARCHAR NOT NULL,',
                '  "criado_em" TIMESTAMP,',
                '  "ativo" BOOLEAN,',
                '  "valor" DOUBLE',
                ");",
            ].join("\n"),
        );
    });

    it("rejeita tipos sem mapeamento quando não há sobrescrita explícita", () => {
        class TabelaSemTipo extends SuperTabela<number> {}
        Reflect.defineMetadata(
            "design:type",
            Object,
            TabelaSemTipo.prototype,
            "dados",
        );

        expect(() =>
            Campo({ colunaNome: "dados" })(TabelaSemTipo.prototype, "dados"),
        ).toThrow(
            "Não foi possível inferir um tipo de dado no banco para TabelaSemTipo.dados (tipo TypeScript: Object).",
        );
    });

    it("gera INSERT parametrizado, omite chave gerada e preserva os valores", () => {
        const insert = new SQLGen().inserirTupla(new TabelaTeste());

        expect(insert).toEqual({
            sql: 'INSERT INTO "teste" ("nome", "criado_em", "ativo", "valor") VALUES (?, ?, ?, ?)',
            parameters: [
                "Orquídea d'água",
                "2026-10-20T16:00:00.000Z",
                false,
                1.5,
            ],
        });
    });

    it("gera INSERT DEFAULT VALUES quando todos os campos são gerados", () => {
        expect(new SQLGen().inserirTupla(new TabelaSomenteId())).toEqual({
            sql: 'INSERT INTO "somente_id" DEFAULT VALUES',
            parameters: [],
        });
    });

    it("gera consultas de listagem e busca por chave primária parametrizada", () => {
        const sqlGen = new SQLGen();

        expect(sqlGen.selecionarTodos(TabelaTeste)).toBe(
            'SELECT * FROM "teste"',
        );
        expect(sqlGen.selecionarPorPk(TabelaTeste)).toBe(
            'SELECT * FROM "teste" WHERE "id" = ?',
        );
    });

    it("informa o campo obrigatório ausente", () => {
        expect(() =>
            new SQLGen().inserirTupla(new TabelaObrigatoriaInvalida()),
        ).toThrow(
            "Campos obrigatórios não preenchidos em TabelaObrigatoriaInvalida: nome.",
        );
    });

    it("rejeita valores incompatíveis com o tipo de dado e identifica o campo", () => {
        expect(() =>
            new SQLGen().inserirTupla(new TabelaValorInvalido()),
        ).toThrow(
            "Valor inválido em TabelaValorInvalido.valor: Valor incompatível com o tipo de dado DOUBLE.",
        );
    });

    it("executa a inserção e retorna o resultado do driver", async () => {
        const result: SQLExecutionResult = { lastID: 12, changes: 1 };
        const query = jest.fn(
            async (_sql: string, _parameters: unknown[]) => result,
        );
        const executor = new SQLInsertExecutor(
            { query } satisfies SQLQueryExecutor,
        );

        await expect(executor.inserir(new TabelaTeste())).resolves.toBe(result);
        expect(query).toHaveBeenCalledWith(
            'INSERT INTO "teste" ("nome", "criado_em", "ativo", "valor") VALUES (?, ?, ?, ?)',
            ["Orquídea d'água", "2026-10-20T16:00:00.000Z", false, 1.5],
        );
    });

    it("propaga erros do executor do banco", async () => {
        const erro = new Error("Falha de constraint");
        const query: SQLQueryExecutor = {
            query: async () => {
                throw erro;
            },
        };
        const executor = new SQLInsertExecutor(query);

        await expect(executor.inserir(new TabelaTeste())).rejects.toBe(erro);
    });
});
