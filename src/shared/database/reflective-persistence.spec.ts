const testDatabases: DatabaseSync[] = [];

class InMemorySQLiteDriver implements SQLiteDriver {
  open(
    _filename: string,
    callback: (error: (Error & { code?: string }) | null) => void,
  ): SQLiteConnection {
    const database = new DatabaseSync(':memory:');
    testDatabases.push(database);

    const connection: SQLiteConnection = {
      run: (sql, parameters, runCallback) => {
        try {
          let lastID = 0;
          let changes = 0;

          if (sql.startsWith('CREATE TABLE')) {
            database.exec(sql);
          } else {
            const values = parameters.map((parameter) => {
              if (
                parameter === null ||
                typeof parameter === 'string' ||
                typeof parameter === 'number' ||
                typeof parameter === 'bigint' ||
                parameter instanceof Uint8Array
              ) {
                return parameter;
              }
              throw new TypeError('Unsupported SQLite test parameter');
            });
            const result = database.prepare(sql).run(...values);
            lastID = Number(result.lastInsertRowid);
            changes = Number(result.changes);
          }

          queueMicrotask(() => {
            runCallback.call({ lastID, changes }, null);
          });
        } catch (error) {
          queueMicrotask(() => {
            runCallback.call(
              { lastID: 0, changes: 0 },
              error instanceof Error ? error : new Error(String(error)),
            );
          });
        }
      },
      all: (sql, parameters, allCallback) => {
        try {
          const rows = database
            .prepare(sql)
            .all(...parameters) as Record<string, unknown>[];
          queueMicrotask(() => allCallback(null, rows));
        } catch (error) {
          queueMicrotask(() =>
            allCallback(
              error instanceof Error ? error : new Error(String(error)),
              [],
            ),
          );
        }
      },
      get: (sql, parameters, getCallback) => {
        try {
          const row = database
            .prepare(sql)
            .get(...parameters) as Record<string, unknown> | undefined;
          queueMicrotask(() => getCallback(null, row));
        } catch (error) {
          queueMicrotask(() =>
            getCallback(
              error instanceof Error ? error : new Error(String(error)),
            ),
          );
        }
      },
      close: (closeCallback) => {
        database.close();
        closeCallback(null);
      },
    };

    queueMicrotask(() => callback(null));
    return connection;
  }
}

/*
 * The production driver is sqlite3; this adapter exercises the database
 * lifecycle against Node's in-memory SQLite without requiring a native addon.
 */
@Tabela({ tableName: 'injection_test' })
class InjectionTestEntity extends SuperTabela<number> {
  @Campo({
    colunaNome: 'id',
    isPk: true,
    isObrigatorio: true,
    isAutoGenerated: true,
  })
  id: number;

  @Campo({ colunaNome: 'name', isObrigatorio: true })
  name: string;

  @Campo({
    colunaNome: 'active',
    dataType: DatabaseDataType.BOOLEAN,
  })
  active: boolean;

  constructor(id: number, name: string, active: boolean) {
    super();
    this.id = id;
    this.name = name;
    this.active = active;
  }
}

@Injetavel()
class InjectionTestConsumer {
  constructor(
    @Injetar(InjectionTestEntity)
    readonly repository: ReflectiveRepository<InjectionTestEntity>,
  ) {}
}

describe('custom reflective persistence', () => {
  it('injects the entity-specific reflective repository with custom decorators', async () => {
    const repository = new ReflectiveRepository(InjectionTestEntity, {
      query: jest.fn(),
      queryAll: jest.fn(),
      queryOne: jest.fn(),
    });
    const moduleRef = await Test.createTestingModule({
      providers: [
        InjectionTestConsumer,
        {
          provide: getEntityRepositoryToken(InjectionTestEntity),
          useValue: repository,
        },
      ],
    }).compile();

    expect(moduleRef.get(InjectionTestConsumer).repository).toBe(repository);
    await moduleRef.close();
  });

  it('creates a reflected SQLite table and inserts a row with a generated primary key', async () => {
    const database = new SQLiteDatabase(
      ':memory:',
      [InjectionTestEntity],
      new InMemorySQLiteDriver(),
    );
    await database.onModuleInit();

    try {
      const repository = new ReflectiveRepository(
        InjectionTestEntity,
        database,
      );
      const result = await repository.inserir(
        new InjectionTestEntity(0, 'orchid', true),
      );

      expect(result.lastID).toBeGreaterThan(0);
      expect(result.changes).toBe(1);
      expect(
        testDatabases[testDatabases.length - 1]
          .prepare('SELECT name, active FROM "injection_test"')
          .get(),
      ).toEqual({ name: 'orchid', active: 1 });
    } finally {
      await database.onModuleDestroy();
    }
  });

  it('lists rows and finds one by a parameterized primary key', async () => {
    const database = new SQLiteDatabase(
      ':memory:',
      [InjectionTestEntity],
      new InMemorySQLiteDriver(),
    );
    await database.onModuleInit();

    try {
      const repository = new ReflectiveRepository(
        InjectionTestEntity,
        database,
      );
      const inserted = await repository.inserir(
        new InjectionTestEntity(0, 'orchid', true),
      );

      await expect(repository.listar()).resolves.toEqual([
        expect.objectContaining({
          id: inserted.lastID,
          name: 'orchid',
          active: 1,
        }),
      ]);
      await expect(repository.buscarPorPk(inserted.lastID)).resolves.toEqual({
        id: inserted.lastID,
        name: 'orchid',
        active: 1,
      });
      await expect(repository.buscarPorPk(999)).resolves.toBeUndefined();
    } finally {
      await database.onModuleDestroy();
    }
  });

  it('maps persisted orquidarios back to the domain, including dates and booleans', async () => {
    const database = new SQLiteDatabase(
      ':memory:',
      [OrquidarioEntity],
      new InMemorySQLiteDriver(),
    );
    await database.onModuleInit();

    try {
      const repository = new OrquidarioRepository(
        new ReflectiveRepository(OrquidarioEntity, database),
      );
      const created = await repository.create(
        new Orquidario(
          0,
          'Avenida Presidente Kennedy',
          new Date('2026-01-09T00:00:00.000Z'),
          true,
          55,
        ),
      );

      await expect(repository.findAll()).resolves.toEqual([created]);
      await expect(repository.findById(created.id)).resolves.toEqual(created);
      await expect(repository.findById(999)).resolves.toBeUndefined();
      expect(created.dataCriacao).toBeInstanceOf(Date);
      expect(created.irrigadoAuto).toBe(true);
    } finally {
      await database.onModuleDestroy();
    }
  });
});
